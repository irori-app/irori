def spec(version: str, repo: str, day: datetime.date | None = None) -> str:
    """The COPR package. Its sources are the release's tarballs by name, so
    `rpmbuild -bs` takes them from the release's files."""
    day = day or datetime.datetime.now(datetime.timezone.utc).date()
    # rpm wants English day and month names whatever the locale.
    date = f"{DAYS[day.weekday()]} {MONTHS[day.month - 1]} {day.day:02d} {day.year}"
    return SPEC.format(version=version, repo=repo, homepage=HOMEPAGE, summary=SUMMARY, date=date)


DAYS = ("Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun")
MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


WINGET_SCHEMA = "1.6.0"
WINGET_ID = "Irori.Irori"


def inno_product_code(script: Path = INNO_SCRIPT) -> str:
    """The Windows setup's uninstall key, which winget matches installs by:
    Inno Setup's `AppId` (written `{{` in the script) and `_is1`."""
    match = re.search(r"^AppId=\{(\{[0-9A-Fa-f-]+\})\s*$", script.read_text(), re.MULTILINE)
    if not match:
        raise ValueError(f"No AppId in {script}")
    return f"{match.group(1)}_is1"


def winget(version: str, repo: str, x64_sha: str, arm64_sha: str) -> dict[str, str]:
    """The three manifests winget-pkgs takes for a version. The installer's
    custom switch makes the setup write `Channel=winget` to `install.ini`, so
    Irori offers `winget upgrade` rather than the release page."""
    base = f"https://github.com/{repo}/releases/download/v{version}"
    folder = f"winget/manifests/i/Irori/Irori/{version}"
    head = lambda kind: (f"# Generated by packaging/release_manifests.py for each release.\n"
                         f"# yaml-language-server: $schema=https://aka.ms/winget-manifest.{kind}.{WINGET_SCHEMA}.schema.json\n\n"
                         f"PackageIdentifier: {WINGET_ID}\nPackageVersion: {version}\n")
    tail = lambda kind: f"ManifestType: {kind}\nManifestVersion: {WINGET_SCHEMA}\n"
    return {
        f"{folder}/{WINGET_ID}.yaml": head("version") + "DefaultLocale: en-US\n" + tail("version"),
        f"{folder}/{WINGET_ID}.installer.yaml": head("installer") + f"""\
InstallerType: inno
Scope: user
InstallModes:
- interactive
- silent
- silentWithProgress
InstallerSwitches:
  Custom: /CHANNEL=winget
UpgradeBehavior: install
ProductCode: '{inno_product_code()}'
Protocols:
- irori
Installers:
- Architecture: x64
  InstallerUrl: {base}/Irori-{version}-windows-setup.exe
  InstallerSha256: {x64_sha.upper()}
- Architecture: arm64
  InstallerUrl: {base}/Irori-{version}-windows-arm64-setup.exe
  InstallerSha256: {arm64_sha.upper()}
""" + tail("installer"),
        f"{folder}/{WINGET_ID}.locale.en-US.yaml": head("defaultLocale") + f"""\
PackageLocale: en-US
Publisher: Irori developers
PublisherUrl: {HOMEPAGE}
PublisherSupportUrl: https://github.com/{repo}/issues
PackageName: Irori
PackageUrl: {HOMEPAGE}
License: MIT
LicenseUrl: https://github.com/{repo}/blob/v{version}/LICENSE
ShortDescription: {SUMMARY}
Description: A native game launcher for Epic Games, GOG, Amazon Games, ZOOM Platform, itch.io, Steam and emulators.
Tags:
- games
- game-launcher
- epic-games
- gog
- emulation
ReleaseNotesUrl: https://github.com/{repo}/releases/tag/v{version}
""" + tail("defaultLocale"),
    }


def flathub(version: str, repo: str, commit: str, manifest: str) -> str:
    """The Flatpak manifest CI builds from a checkout, with its `dir` source
    replaced by the release's tag and commit, as Flathub requires."""
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise ValueError(f"Not a full commit hash: {commit}")
    lines = manifest.splitlines()
    starts = [i for i, line in enumerate(lines) if re.fullmatch(r"\s*- type: dir", line)]
    if len(starts) != 1:
        raise ValueError("The Flatpak manifest must have exactly one `dir` source")
    start = starts[0]
    indent = lines[start][: len(lines[start]) - len(lines[start].lstrip())]
    end = start + 1
    while end < len(lines) and lines[end].startswith(indent + "  "):
        end += 1
    source = [f"{indent}- type: git",
              f"{indent}  url: https://github.com/{repo}.git",
              f"{indent}  tag: v{version}",
              f"{indent}  commit: {commit}"]
    header = ["# Generated by packaging/release_manifests.py from packaging/flatpak/app.irori.Irori.yml",
              f"# in {repo} for v{version}. cargo-sources.json comes from the same tag's Cargo.lock."]
    return "\n".join([*header, *lines[:start], *source, *lines[end:]]) + "\n"


def render(version: str, dist: Path, repo: str, commit: str | None = None,
           flatpak_manifest: str | None = None) -> dict[str, str]:
    """Manifest contents keyed by their path under the output folder."""
    found = artifacts(version, dist)
    files = {
        "aur/PKGBUILD": pkgbuild(version, repo, sha256(found["linux"])),
        "homebrew/Casks/irori.rb": CASK.format(
            version=version, repo=repo, homepage=HOMEPAGE,
            arm_sha=sha256(found["macos-arm64"]), intel_sha=sha256(found["macos-x86_64"])),
        "scoop/bucket/irori.json": scoop(version, repo, sha256(found["windows"]), sha256(found["windows-arm64"])),
        "copr/irori.spec": spec(version, repo),
        **winget(version, repo, sha256(found["windows-setup"]), sha256(found["windows-arm64-setup"])),
    }
    if commit:
        manifest = flatpak_manifest if flatpak_manifest is not None else FLATPAK_MANIFEST.read_text()
        files["flathub/app.irori.Irori.yml"] = flathub(version, repo, commit, manifest)
    return files


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--version", required=True)
    parser.add_argument("--dist", type=Path, required=True)
    parser.add_argument("--repo", required=True, help="owner/name on GitHub")
    parser.add_argument("--output", type=Path, required=True)
    only = parser.add_mutually_exclusive_group()
    only.add_argument("--arch-repository", action="store_true",
                      help="only write arch/PKGBUILD, for Irori's own pacman repository; needs only the Linux tarball")
    only.add_argument("--aur", action="store_true", help="only write aur/PKGBUILD; needs only the Linux tarball")
    only.add_argument("--copr", action="store_true", help="only write copr/irori.spec; needs only the Linux tarballs")
    parser.add_argument("--commit", help="the tag's commit: also write flathub/app.irori.Irori.yml")
    parser.add_argument("--flatpak-manifest", type=Path, default=FLATPAK_MANIFEST,
                        help="the Flatpak manifest to pin (the tag's own)")
    args = parser.parse_args()
    version = args.version.removeprefix("v")
    if args.arch_repository or args.aur:
        tarball = artifacts(version, args.dist, ("linux",))["linux"]
        name = "aur" if args.aur else "arch"
        files = {f"{name}/PKGBUILD": pkgbuild(version, args.repo, sha256(tarball), aur=args.aur)}
    elif args.copr:
        artifacts(version, args.dist, ("linux", "linux-arm64"))
        files = {"copr/irori.spec": spec(version, args.repo)}
    else:
        files = render(version, args.dist, args.repo, args.commit, args.flatpak_manifest.read_text())
    for relative, content in files.items():
        path = args.output / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(path)
